// Map Utah zips to area keys. Thin local sets fall back to Salt Lake.
window.LSA_zipToArea = function (zip) {
  if (!/^84\d{3}$/.test(zip)) return null;

  var sandy = { "84070":1, "84092":1, "84093":1, "84094":1 };
  var southJordan = { "84009":1, "84095":1, "84081":1 };
  var davis = { "84010":1, "84011":1, "84014":1, "84015":1, "84025":1, "84037":1, "84040":1, "84041":1, "84054":1, "84075":1, "84087":1 };

  function pack(key, note) {
    return { key: key, heading: "Senior living communities near " + zip, note: note || null };
  }

  if (zip.indexOf("844") === 0) return pack("ogden");
  if (zip.indexOf("847") === 0) return pack("st-george");
  if (zip.indexOf("846") === 0) return pack("utah-county");
  if (zip.indexOf("843") === 0) return pack("logan");
  if (zip.indexOf("841") === 0) return pack("salt-lake");
  if (sandy[zip]) return pack("sandy");
  if (southJordan[zip]) return pack("south-jordan");
  if (davis[zip]) return pack("davis");
  // Other 840xx and remaining Utah zips: Salt Lake is the nearest published metro set.
  return pack("salt-lake", "Showing Salt Lake City communities, the closest published set for this Utah zip.");
};
